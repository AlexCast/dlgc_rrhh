            <h2>2. Datos personales que tratamos</h2>
            <p>Tratamos los datos personales necesarios para la gestión de recursos humanos, tales como:</p>
            <ul>
                <li>Nombres y apellidos, tipo y número de documento de identidad.</li>
                <li>Correo electrónico personal y corporativo, teléfono de contacto.</li>
                <li>Dirección de residencia y datos de contacto de familiares o beneficiarios.</li>
                <li>Información laboral: cargo, área, contrato, jefe inmediato, afiliaciones.</li>
                <li>Documentos soporte de afiliaciones (EPS, ARL, fondo de pensiones, caja de compensación).</li>
                <li>Solicitudes de permisos, vacaciones e incapacidades, incluyendo evidencias de soporte.</li>
                <li>Quejas, sugerencias o reportes relacionados con el programa de Seguridad y Salud en el Trabajo (SST).</li>
            </ul>
            <p>
                <strong>No solicitamos ni almacenamos historias clínicas completas.</strong> Únicamente recibimos la
                evidencia mínima requerida para el trámite correspondiente, como la constancia de la cita médica.
            </p>
        </section>

        <section class="legal-section">
            <h2>3. Finalidad del tratamiento</h2>
            <p>Utilizamos los datos personales para las siguientes finalidades:</p>
            <ul>
                <li>Gestionar la activación de cuentas, autenticación y recuperación de acceso al portal.</li>
                <li>Administrar solicitudes de permisos, vacaciones e incapacidades.</li>
                <li>Notificar al jefe inmediato y al área de Recursos Humanos sobre solicitudes pendientes.</li>
                <li>Gestionar comunicados internos y consulta de información corporativa.</li>
                <li>Atender quejas y sugerencias del programa SST.</li>
                <li>Cumplir con obligaciones legales y laborales.</li>
            </ul>
        </section>

        <section class="legal-section">
            <h2>4. Base legal</h2>
            <p>
                El tratamiento de datos personales se realiza con fundamento en el artículo 10 de la Ley 1581 de 2012,
                correspondiente al <strong>deber legal del empleador</strong> y a la <strong>relación laboral</strong>
                existente con el colaborador. En el caso de datos sensibles (salud, afiliaciones), se aplican las
                excepciones previstas en el artículo 13 de la Ley 1581 de 2012 y el numeral 7 del artículo 6 del
                Decreto 1377 de 2013.
            </p>
        </section>

        <section class="legal-section">
            <h2>5. Almacenamiento y seguridad</h2>
            <p>
                La información se almacena en servidores propios y en infraestructura de almacenamiento en la nube
                <strong>Cloudflare R2</strong>, ubicada fuera de Colombia. Los documentos laborales, contratos,
                afiliaciones y evidencias de soporte se guardan de forma cifrada y con controles de acceso estrictos.
            </p>
            <p>
                Implementamos medidas técnicas y administrativas para proteger la información, incluyendo:
                autenticación segura, tokens CSRF, cookies HttpOnly y SameSite, control de permisos por módulo,
                auditoría mediante triggers de base de datos y expiración de sesiones por inactividad.
            </p>
        </section>

        <section class="legal-section">
            <h2>6. Comunicaciones por correo electrónico</h2>
            <p>
                El portal envía correos electrónicos transaccionales para: verificación de cuenta, recuperación de
                contraseña, notificaciones de solicitudes de permisos, notificaciones SST y alertas de aprobación o
                rechazo. Estos correos son necesarios para el funcionamiento del servicio y se envían únicamente a
                las direcciones registradas por el propio usuario o por el área de Recursos Humanos.
            </p>
        </section>

        <section class="legal-section">
